import numpy as np

# Исходные данные
A = np.array([   
    [4.75, -1.32,  0.21, -0.67],   
    [-0.45, 5.02,  1.43,  0.34],   
    [0.98,  0.76,  3.51, -0.12],   
    [-0.32, 0.54, -0.87,  6.23]   
])

print("Исходная матрица A:")
print(A)
# ============================================================================
# ПОДГОТОВКА К МЕТОДУ КВАДРАТНОГО КОРНЯ
# Метод квадратного корня требует симметричную положительно 
# определённую матрицу. Так как исходная матрица A не симметрична, 
# переходим к нормальным уравнениям: A^T * A * x = A^T * b
# ============================================================================

M = A.T @ A

print("\nСимметричная матрица M = A^T * A:")
print(np.round(M, 4))

# ============================================================================
# 1. РАЗЛОЖЕНИЕ ХОЛЕЦКОГО: M = L * L^T
# ============================================================================

n = len(M)
L = np.zeros((n, n), dtype=float)

for i in range(n):
    for j in range(i + 1):
        sum_val = sum(L[i][k] * L[j][k] for k in range(j))
        
        if i == j:
            val = M[i][i] - sum_val
            if val <= 0:
                raise ValueError("Матрица не является положительно определённой")
            L[i][j] = np.sqrt(val)
        else:
            L[i][j] = (M[i][j] - sum_val) / L[j][j]

print("\nМатрица L (нижняя треугольная):")
print(np.round(L, 4))

# ============================================================================
# 2. ВЫЧИСЛЕНИЕ ОПРЕДЕЛИТЕЛЯ
# ============================================================================

# det(M) = det(L) * det(L^T) = (произведение диагональных элементов L)^2
diag_L = [L[i][i] for i in range(n)]
det_M = 1.0
for val in diag_L:
    det_M *= val
det_M = det_M ** 2

# det(A^T * A) = det(A) * det(A^T) = det(A)^2
# Так как матрица A диагонально преобладает, её определитель положителен:
det_A = np.sqrt(det_M)

print(f"\nОпределитель матрицы M = A^T * A: {det_M:.6f}")
print(f"Определитель исходной матрицы A:  {det_A:.6f}")
